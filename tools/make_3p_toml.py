#!/usr/bin/env python3
"""Writes game_3p.toml, the three-player configuration, from game.toml.

game.toml is the two-player configuration (2 controller seats) and the one
the recompiler reads. Three players (a third pad on an SCPH-1070 multitap on
port 2; needs a build with -DBBT_MAX_PLAYERS=5) differ only in:
  [game]        players = 3
  [controller]  multitap_port = 2, multitap_analog = false
Everything else (timing, netplay, paths) is copied, so the two never drift
apart (tests/test_unit_tools.py checks that the committed game_3p.toml is
exactly this output). Relative paths stay relative to the repository.

Usage (from the repository root):  python3 tools/make_3p_toml.py [--check]
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = ("# GENERATED by tools/make_3p_toml.py from game.toml: three players (a\n"
          "# multitap on port 2, a build with -DBBT_MAX_PLAYERS=5). Do not edit;\n"
          "# change game.toml and run the tool again.\n")


def three_player(text: str) -> str:
    out, section, seen_controller = [], None, False
    done = {"multitap_port": False, "multitap_analog": False}

    def close_controller():
        if section == "controller":
            if not done["multitap_port"]:
                out.append("multitap_port = 2")
            if not done["multitap_analog"]:
                out.append("multitap_analog = false")

    for line in text.splitlines():
        s = line.strip()
        if s.startswith("[") and s.endswith("]") and not s.startswith("[["):
            close_controller()
            section = s[1:-1]
            seen_controller |= section == "controller"
        elif section == "game" and s.split("=")[0].strip() == "players":
            line = "players = 3"
        elif section == "controller" and s.split("=")[0].strip() in done:
            key = s.split("=")[0].strip()
            line = "multitap_port = 2" if key == "multitap_port" else "multitap_analog = false"
            done[key] = True
        out.append(line)
    close_controller()
    if not seen_controller:
        out += ["", "[controller]", "multitap_port = 2", "multitap_analog = false"]
    return HEADER + "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    src, dst = ROOT / "game.toml", ROOT / "game_3p.toml"
    want = three_player(src.read_text(encoding="utf-8"))
    if "--check" in argv:
        have = dst.read_text(encoding="utf-8") if dst.is_file() else ""
        # the launcher writes its multitap-analog choice into its --game file
        strip = lambda text: [l for l in text.splitlines() if not l.strip().startswith("multitap_analog")]
        if strip(have) != strip(want):
            print("game_3p.toml is out of date: run python3 tools/make_3p_toml.py", file=sys.stderr)
            return 1
        print("game_3p.toml is up to date")
        return 0
    dst.write_text(want, encoding="utf-8")
    print(f"wrote {dst}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
